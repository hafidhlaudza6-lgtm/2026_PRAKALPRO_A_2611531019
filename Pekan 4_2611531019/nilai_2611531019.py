# Nama variabel ditambah 4 digit nim terakhir contoh: ipk_1234
# Program ini menggunakan fungsi input()
# program konversi nilai angka menjadi huruf

nilai_1019 = int(input("Inputkan nilai angka= "))

if nilai_1019 >= 81:
    print("A")
elif nilai_1019 >= 70:
    print("B")
elif nilai_1019 >= 60:
    print("C")
elif nilai_1019 >= 50:
    print("D")
else:
    print("E")